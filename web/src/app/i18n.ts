export const DICTIONARIES: Record<Language, Messages> = { en: EN, fr: FR, hu: HU };

export type MsgParams = Record<string, string | number | undefined>;

/** A translatable message kept as data so it re-renders when the language changes. */
export interface Msg {
  key: MessageKey;
  params?: MsgParams;
}

const current = signal<Language>('en');

/** The language the texts are in; reading it inside a template or computed follows language changes. */
export const language = current.asReadonly();

export function setLanguage(next: Language): void {
  current.set(next);
}

export function isLanguage(value: unknown): value is Language {
  return LANGUAGES.some((l) => l.id === value);
}

export function t(key: MessageKey, params?: MsgParams): string {
  const text = DICTIONARIES[current()][key];
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
}

export const tm = (msg: Msg): string => t(msg.key, msg.params);

/** Localized name of a palette color (its swatch's accessible name); older colors fall back to their key. */
export const colorName = (key: string): string => DICTIONARIES[current()][`color.${key}` as MessageKey] ?? key;
